#!/bin/bash
# oryx-wheel2pkg.sh -- turn a pure-Python PyPI wheel into an Oryx package.
#
#   oryx-wheel2pkg.sh [-n NAME] [-D dep]... WHEEL [OUTDIR]
#
# Why this exists: RNS, LXMF and NomadNet are not in Debian at all, so
# deb2pkg-dell.sh has nothing to convert. Their wheels are py3-none-any --
# pure Python, no compiled extension -- so the amd64 Dell can stage them for
# the i686 Hurd target without any cross toolchain. That is the whole trick.
#
# Files land in /usr/lib/python3/dist-packages, which is where Debian's
# python3-* packages already put theirs and is on the target's sys.path.
# NOTE: it is NOT sysconfig's purelib (that is /usr/local/lib/...); we follow
# Debian's layout because every other package in the repo does.
#
# Console scripts are NOT in a wheel -- pip generates them from
# dist-info/entry_points.txt at install time. Since nothing runs pip on the
# target, this script generates them itself, or `rnsd` and `nomadnet` would
# simply not exist after `pacman -S`.
set -euo pipefail

NAME=; DEPS=()
while getopts "n:D:" o; do
    case "$o" in
        n) NAME=$OPTARG ;;
        D) DEPS+=("$OPTARG") ;;
        *) echo "usage: $0 [-n NAME] [-D dep]... WHEEL [OUTDIR]" >&2; exit 2 ;;
    esac
done
shift $((OPTIND - 1))

WHEEL=${1:-}; OUT=${2:-$HOME/Desktop/hurd/repo}
[ -f "${WHEEL:-}" ] || { echo "usage: $0 [-n NAME] [-D dep]... WHEEL [OUTDIR]" >&2; exit 2; }
WHEEL=$(readlink -f "$WHEEL")
HERE=$(cd "$(dirname "$0")" && pwd)

base=$(basename "$WHEEL" .whl)
dist=${base%%-*}                       # e.g. rns
ver=$(echo "$base" | cut -d- -f2)      # e.g. 1.5.4
: "${NAME:=python3-$(echo "$dist" | tr '[:upper:]_' '[:lower:]-')}"

STAGE=$(mktemp -d)
trap 'rm -rf "$STAGE"' EXIT
SITE=$STAGE/usr/lib/python3/dist-packages
mkdir -p "$SITE" "$STAGE/usr/bin"

unzip -q "$WHEEL" -d "$SITE"

# A wheel's <dist>-<ver>.data/scripts/ holds pre-built scripts; those go to
# /usr/bin. .data/ itself must not stay in site-packages.
shopt -s nullglob
for d in "$SITE"/*.data; do
    [ -d "$d/scripts" ] && { cp -a "$d/scripts/." "$STAGE/usr/bin/"; }
    rm -rf "$d"
done

# Generate console scripts from entry_points.txt, exactly as pip would.
for ep in "$SITE"/*.dist-info/entry_points.txt; do
    [ -f "$ep" ] || continue
    python3 - "$ep" "$STAGE/usr/bin" <<'PY'
import configparser, os, stat, sys
ep, bindir = sys.argv[1], sys.argv[2]
cp = configparser.ConfigParser(); cp.optionxform = str; cp.read(ep)
if not cp.has_section("console_scripts"): raise SystemExit(0)
for name, target in cp.items("console_scripts"):
    mod, _, attr = target.partition(":")
    attr = attr.strip() or "main"
    path = os.path.join(bindir, name)
    with open(path, "w") as f:
        f.write("#!/usr/bin/python3\n"
                "# Generated by oryx-wheel2pkg.sh (pip does not run on the target).\n"
                "import re, sys\n"
                f"from {mod} import {attr.split('.')[0]}\n"
                "if __name__ == '__main__':\n"
                "    sys.argv[0] = re.sub(r'(-script\\.pyw|\\.exe)?$', '', sys.argv[0])\n"
                f"    sys.exit({attr}())\n")
    os.chmod(path, 0o755)
    print("  script: /usr/bin/%s -> %s:%s" % (name, mod, attr), file=sys.stderr)
PY
done
shopt -u nullglob
rmdir "$STAGE/usr/bin" 2>/dev/null || true

# Byte-compiling here would be wrong: the Dell runs CPython 3.13 and the
# target 3.14, and a .pyc carries a magic number the target would reject.
# Python falls back to the source silently, so leaving them out is correct.
find "$SITE" -name '__pycache__' -type d -prune -exec rm -rf {} + 2>/dev/null || true

args=(-n "$NAME" -v "${ver}-1" -a any -d "$dist $ver (PyPI wheel, packaged for Oryx)")
for d in ${DEPS+"${DEPS[@]}"}; do args+=(-D "$d"); done
"$HERE/oryx-mkpkg.sh" "${args[@]}" "$STAGE" "$OUT"
